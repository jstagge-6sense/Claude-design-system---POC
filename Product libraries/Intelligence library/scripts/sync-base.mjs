// One-way mirror of the 6sense design system (the repo root, two folders up) into ./base, so this folder holds everything
// from the design system: components, icons, styles, tokens, built token CSS, scripts, docs and charts.
// The original stays the single source of truth. Never edit ./base: change the original, then sync.
// Usage: node scripts/sync-base.mjs            (once)
//        node scripts/sync-base.mjs --watch    (keep ./base up to date as the original changes)
import { cpSync, rmSync, existsSync, mkdirSync, writeFileSync, watch, statSync } from 'node:fs'
import { join, dirname, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const lib = join(here, '..')
const root = join(lib, '..', '..')
const out = join(lib, 'base')
const PARTS = ['src', 'tokens', 'dist', 'scripts', 'docs', 'Data-Viz', 'package.json']
const skip = (p) => p.split(sep).some((s) => s === 'node_modules' || s === '.DS_Store' || s === '_unused')

function sync() {
  if (!existsSync(root + '/src')) { console.error(`The design system was not found at ${root}.`); process.exit(1) }
  mkdirSync(out, { recursive: true })
  for (const part of PARTS) {
    const from = join(root, part)
    if (!existsSync(from)) { console.warn(`skipped (not in the original): ${part}`); continue }
    rmSync(join(out, part), { recursive: true, force: true })
    cpSync(from, join(out, part), { recursive: true, filter: (s) => !skip(s) })
  }
  writeFileSync(join(out, 'README.md'), '# Mirror of the 6sense design system\n\nGenerated by `npm run sync`. Do not edit here: change the original at the repo root, then sync.\n')
  console.log(`Synced the design system into base/ at ${new Date().toLocaleTimeString()}`)
}

sync()
if (process.argv.includes('--watch')) {
  let t
  const queue = () => { clearTimeout(t); t = setTimeout(sync, 400) }
  for (const part of PARTS.filter((p) => existsSync(join(root, p)) && statSync(join(root, p)).isDirectory())) watch(join(root, part), { recursive: true }, (_e, f) => { if (f && !skip(f)) queue() })
  console.log('Watching the original design system. Press Ctrl+C to stop.')
}
