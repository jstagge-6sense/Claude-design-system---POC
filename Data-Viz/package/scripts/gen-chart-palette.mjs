#!/usr/bin/env node
// Generates src/charts/palette.generated.ts from the 6DS primitive color tokens (tokens/primitive/color.json).
// Chart colors are 6DS colors only: no hex is typed by hand, and no Highcharts default colors are used.
//
// Rules applied:
//  - A step is usable in a chart only if it has >= 3:1 contrast against white (WCAG 1.4.11, graphical objects).
//  - Sequential ramps: evenly spaced usable steps of one 6DS hue, light to dark.
//  - Single color: the middle usable step of the primary hue.
//  - Categorical: hue order chosen for distinctness (checked with Delta E 94), several passes through the hues.
//  - "Other": Ink (a 6DS neutral), so a missing hue still means "different but measured".
// The 6DS system has no semantic data-visualization tokens yet; this file is the chart layer until it does (gap GAP-chart-palette).
// Usage: node scripts/gen-chart-palette.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const tokens = JSON.parse(readFileSync(join(root, 'tokens/primitive/color.json'), 'utf8')).core.color

// ---- configuration ---------------------------------------------------------------------------------------------
const HUES = ['teal', 'blue', 'green', 'amber', 'red', 'ink'] // 6DS hue families with a ramp (sage is a surface neutral, not a data color)
const PRIMARY = 'teal' // 6DS primary (Primary button). Change here to re-base single-color charts.
const CATEGORICAL_HUES = ['blue', 'amber', 'teal', 'red', 'green'] // order: alternate warm/cool, keep similar hues apart
const CATEGORICAL_PASSES = [0.25, 0, 0.6] // position within each hue's usable steps (0 = lightest usable, 1 = darkest)
const OTHER_HUE = 'ink' // 6DS neutral; step most distinct from the first categorical pass (Delta E 94), excluding 900 which is the text color
const MIN_CONTRAST = 3

// ---- color math ------------------------------------------------------------------------------------------------
const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16))
const lin = (v) => { const c = v / 255; return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4 }
const lum = (h) => { const [r, g, b] = rgb(h).map(lin); return 0.2126 * r + 0.7152 * g + 0.0722 * b }
const contrastWhite = (h) => 1.05 / (lum(h) + 0.05)
function lab(h) {
  const [r, g, b] = rgb(h).map(lin)
  const x = (0.4124 * r + 0.3576 * g + 0.1805 * b) / 0.95047
  const y = 0.2126 * r + 0.7152 * g + 0.0722 * b
  const z = (0.0193 * r + 0.1192 * g + 0.9505 * b) / 1.08883
  const f = (t) => (t > 0.008856 ? Math.cbrt(t) : 7.787 * t + 16 / 116)
  return [116 * f(y) - 16, 500 * (f(x) - f(y)), 200 * (f(y) - f(z))]
}
function deltaE94(a, b) {
  const [L1, a1, b1] = lab(a), [L2, a2, b2] = lab(b)
  const C1 = Math.hypot(a1, b1), C2 = Math.hypot(a2, b2)
  const dL = L1 - L2, dC = C1 - C2
  const dH2 = Math.max(0, (a1 - a2) ** 2 + (b1 - b2) ** 2 - dC ** 2)
  return Math.sqrt(dL ** 2 + (dC / (1 + 0.045 * C1)) ** 2 + dH2 / (1 + 0.015 * C1) ** 2)
}

// ---- build -----------------------------------------------------------------------------------------------------
const ramps = {}
for (const hue of HUES) {
  const steps = Object.entries(tokens[hue]).sort((a, b) => Number(a[0]) - Number(b[0]))
  ramps[hue] = steps
    .map(([step, t]) => ({ token: `core.color.${hue}.${step}`, step, hex: t.$value.toLowerCase(), contrast: contrastWhite(t.$value) }))
    .filter((s) => s.contrast >= MIN_CONTRAST) // usable steps, light to dark
}
const at = (hue, pos) => { const r = ramps[hue]; return r[Math.round(pos * (r.length - 1))] }

const categorical = []
for (const pos of CATEGORICAL_PASSES) for (const hue of CATEGORICAL_HUES) categorical.push({ ...at(hue, pos), hue })
const ink900 = { token: 'core.color.ink.900', hex: tokens.ink['900'].$value.toLowerCase() }
const white = { token: 'core.color.white', hex: tokens.white.$value.toLowerCase() }

const pass1First = categorical.slice(0, CATEGORICAL_HUES.length)
const other = ramps[OTHER_HUE].filter((s) => s.step !== '900').map((s) => ({ s, d: Math.min(...pass1First.map((c) => deltaE94(c.hex, s.hex))) })).sort((a, b) => b.d - a.d)[0].s

// Delta E 94 between neighbours inside one pass and across the first pass (advisory; DBA uses it to judge separation)
const report = []
const pass1 = categorical.slice(0, CATEGORICAL_HUES.length)
for (let i = 0; i < pass1.length; i++) for (let j = i + 1; j < pass1.length; j++) report.push([pass1[i].token, pass1[j].token, deltaE94(pass1[i].hex, pass1[j].hex)])
report.push(['categorical pass 1', 'other', Math.min(...pass1.map((c) => deltaE94(c.hex, other.hex)))])
report.sort((a, b) => a[2] - b[2])

const ts = `// GENERATED by scripts/gen-chart-palette.mjs from tokens/primitive/color.json. Do not edit by hand.
// Chart colors are 6DS colors only. Re-run \`npm run gen:chart-palette\` after changing tokens.
export interface PaletteStep { token: string; step: string; hex: string; contrast: number }
export const HUES = ${JSON.stringify(HUES)} as const
export type Hue = (typeof HUES)[number]
export const PRIMARY_HUE: Hue = ${JSON.stringify(PRIMARY)}
export const MIN_CONTRAST = ${MIN_CONTRAST}
/** Usable steps per hue (>= ${MIN_CONTRAST}:1 on white), light to dark. */
export const USABLE: Record<Hue, readonly PaletteStep[]> = ${JSON.stringify(Object.fromEntries(Object.entries(ramps).map(([h, r]) => [h, r.map((s) => ({ ...s, contrast: Math.round(s.contrast * 100) / 100 }))]))
  , null, 2)}
export const CATEGORICAL_STEPS: readonly (PaletteStep & { hue: Hue })[] = ${JSON.stringify(categorical.map((c) => ({ ...c, contrast: Math.round(c.contrast * 100) / 100 })), null, 2)}
export const OTHER_STEP: PaletteStep = ${JSON.stringify({ ...other, contrast: Math.round(other.contrast * 100) / 100 })}
export const INK_TEXT = ${JSON.stringify(ink900)}
export const WHITE = ${JSON.stringify(white)}
`
writeFileSync(join(root, 'src/charts/palette.generated.ts'), ts)

console.log('Usable steps (>=3:1 on white):')
for (const h of HUES) console.log(`  ${h.padEnd(6)} ${ramps[h].map((s) => `${s.step}:${s.hex}`).join(' ')}`)
console.log('\nCategorical (15):', categorical.map((c) => `${c.hue}.${c.step}`).join(' '))
console.log('Other:', other.token, other.hex)
console.log('\nClosest pairs in categorical pass 1 (Delta E 94; DBA targets > 50 for "other", higher is more distinct):')
for (const r of report.slice(0, 4)) console.log(`  ${r[0]} vs ${r[1]}: ${r[2].toFixed(1)}`)
console.log('\nWrote src/charts/palette.generated.ts')
