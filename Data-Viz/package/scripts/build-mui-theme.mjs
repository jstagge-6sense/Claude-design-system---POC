#!/usr/bin/env node
// Generates src/mui/theme.generated.ts: resolved (static) token values for Material UI.
// MUI's palette helpers (alpha, darken, lighten) need real colors, not var(--x), so this resolves light AND dark values at build time.
// Source of truth stays the token JSON. Re-run after any token change: npm run build:mui-theme
// Reads dist/tokens.json (npm run build:tokens first) and dist/modes.json (dark overrides, density modes).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, resolve } from 'node:path'

const root = resolve(process.argv[2] || '.')
const tokens = JSON.parse(readFileSync(join(root, 'dist/tokens.json'), 'utf8'))
const modes = JSON.parse(readFileSync(join(root, 'dist/modes.json'), 'utf8'))
const errors = []

const firstHex = (v) => (String(v).match(/#[0-9a-fA-F]{6}\b/) || [])[0] // gradients become their first stop (MUI needs a solid color)
const lightHex = (name) => { const t = tokens[name]; if (!t) { errors.push(`missing token ${name}`); return '#000000' } return firstHex(t.value) || (errors.push(`${name} has no color`), '#000000') }
const darkHex = (name) => {
  const ov = modes.dark.override[name]
  if (!ov) return lightHex(name)
  const m = ov.match(/^\{([^}]+)\}$/)
  if (!m) { errors.push(`dark override ${name} is not an alias`); return '#000000' }
  const ref = m[1]
  return modes.dark.extend[ref] || lightHex(ref)
}
const num = (name) => { const t = tokens[name]; if (!t) { errors.push(`missing token ${name}`); return 0 } return parseFloat(t.value) }
const px = (name) => { const t = tokens[name]; if (!t) { errors.push(`missing token ${name}`); return 0 } const v = parseFloat(t.value); return /rem$/.test(t.value) ? Math.round(v * 16 * 100) / 100 : v }
const typo = (name) => {
  const t = tokens[name]; if (!t) { errors.push(`missing token ${name}`); return {} }
  const g = (k) => (String(t.value).match(new RegExp(`${k}:\\s*([^;]+)`)) || [])[1]?.trim()
  const lh = g('lineHeight')
  return { fontSize: g('fontSize'), fontWeight: Number(g('fontWeight')), lineHeight: lh && lh.endsWith('%') ? parseFloat(lh) / 100 : lh }
}

const roles = {
  primary: 'core.color.action.primary.default', primaryDark: 'core.color.action.primary.hover',
  inverse: 'core.color.content.inverse',
  secondary: 'core.color.action.secondary.default',
  error: 'core.color.action.destructive.default', errorDark: 'core.color.action.destructive.hover',
  success: 'core.color.status.success', warning: 'core.color.status.warning', info: 'core.color.status.info',
  textPrimary: 'core.color.content.primary', textSecondary: 'core.color.content.secondary', textDisabled: 'core.color.content.disabled',
  border: 'core.color.border.standard', focus: 'core.color.border.focus',
}
const palette = (resolveFn, dark) => Object.fromEntries([
  ...Object.entries(roles).map(([k, n]) => [k, resolveFn(n)]),
  ['page', dark ? resolveFn('core.color.surface.page') : lightHex('core.color.sage.200')], // light page/card tokens are gradients: use their first stop
  ['card', dark ? resolveFn('core.color.surface.card') : lightHex('core.color.sage.100')],
])

const out = {
  light: palette(lightHex, false),
  dark: palette(darkHex, true),
  opacityDivider: num('core.effect.opacity.200'),
  fontFamily: tokens['core.typography.fontFamily.sans']?.value ?? 'sans-serif',
  radius: { control: px('core.dimension.radius.control.medium'), small: px('core.dimension.radius.control.small'), surface: px('core.dimension.radius.surface.medium') },
  control: { medium: px('core.dimension.size.control.height.medium'), small: px('core.dimension.size.control.height.small') },
  spacingUnit: px('core.dimension.space.compact'),
  typography: Object.fromEntries(['heading.1', 'heading.2', 'heading.3', 'heading.4', 'paragraph.1', 'paragraph.2', 'help.1', 'button.1', 'label.1'].map((k) => [k, typo(`core.typography.${k}`)])),
  density: {
    compact: { space: 0.75, control: 0.8 },
    default: { space: 1, control: 1 },
    spacious: { space: 1.25, control: 1.2 },
  },
}
if (errors.length) { console.error('MUI theme build failed:\n- ' + [...new Set(errors)].join('\n- ')); process.exit(1) }
mkdirSync(join(root, 'src/mui'), { recursive: true })
writeFileSync(join(root, 'src/mui/theme.generated.ts'), `// generated by scripts/build-mui-theme.mjs from the token JSON. Do not edit.\nexport const SIXDS_THEME = ${JSON.stringify(out, null, 2)} as const\n`)
console.log(`MUI theme tokens written: light + dark palette (${Object.keys(out.light).length} roles), ${Object.keys(out.typography).length} type styles, 3 densities.`)
