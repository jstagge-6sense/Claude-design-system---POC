#!/usr/bin/env node
// Generates src/storybook/guidelines/<Name>.stories.tsx: one Storybook page per component that has guidelines.
// The text lives only in src/preview/guidelines*; these files just point at it. Re-run after adding a component.
import { mkdirSync, writeFileSync, readdirSync, existsSync, rmSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { createRequire } from 'node:module'
const root = resolve('.')
const req = createRequire(import.meta.url)
let esbuild
try { esbuild = req(process.env.ESBUILD_PATH || 'esbuild') } catch { esbuild = req('/usr/local/lib/node_modules_global/lib/node_modules/tsx/node_modules/esbuild') }
await esbuild.build({ entryPoints: [join(root, 'src/preview/guidelines.ts')], bundle: true, outfile: '/tmp/ds-guidelines-sb.cjs', platform: 'node', format: 'cjs', logLevel: 'error' })
const { GUIDELINES } = req('/tmp/ds-guidelines-sb.cjs')
const out = join(root, 'src/storybook/guidelines')
mkdirSync(out, { recursive: true })
for (const f of readdirSync(out)) if (f.endsWith('.stories.tsx')) rmSync(join(out, f))
let n = 0
for (const name of Object.keys(GUIDELINES).sort()) {
  const stories = join(root, 'src/components', name, `${name}.stories.tsx`)
  if (!existsSync(stories)) continue
  writeFileSync(join(out, `${name}.stories.tsx`), `// Generated by scripts/gen-storybook-guidelines.mjs. Do not edit.
import type { Meta, StoryObj } from '@storybook/react'
import * as mod from '../../components/${name}/${name}.stories'
import { GuidelinesStory } from '../GuidelinesStory'

const meta = { title: 'Guidelines/${name.replace(/([a-z0-9])([A-Z])/g, '$1 $2')}', parameters: { layout: 'padded' } } satisfies Meta
export default meta
export const Guidelines: StoryObj<typeof meta> = { render: () => <GuidelinesStory folder="${name}" mod={mod as unknown as Record<string, unknown>} /> }
`)
  n++
}
console.log(`Wrote ${n} Storybook guideline pages to src/storybook/guidelines`)
