#!/usr/bin/env node
// Reads the component folders and writes the stack map: what each component is built with, and which components use each other.
//   src/preview/stackMap.json  (read by the preview's Tech stack page)
//   docs/COMPONENT_MAP.md      (generated, same facts as a table)
// Usage: node scripts/gen-stack-map.mjs [repo root]
import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from 'node:fs'
import { join, resolve } from 'node:path'

const root = resolve(process.argv[2] ?? '.')
const comps = join(root, 'src/components')
const names = readdirSync(comps).filter((d) => statSync(join(comps, d)).isDirectory()).sort()
const isSrc = (f) => /\.(ts|tsx)$/.test(f) && !/\.(stories|test|figma)\.tsx?$/.test(f)
const data = names.map((name) => {
  const dir = join(comps, name)
  const files = readdirSync(dir)
  const src = files.filter(isSrc).map((f) => readFileSync(join(dir, f), 'utf8')).join('\n')
  const css = files.filter((f) => f.endsWith('.css')).map((f) => readFileSync(join(dir, f), 'utf8')).join('\n')
  const uses = new Set(), runtime = new Set()
  for (const m of src.matchAll(/from '([^']+)'/g)) {
    const p = m[1]
    const c = p.match(/^\.\.\/([A-Za-z]+)(?:\/|$)/)
    if (c && c[1] !== name && names.includes(c[1])) uses.add(c[1])
    if (/^(react|react-dom)(\/|$)/.test(p)) runtime.add(p.split('/')[0])
  }
  const refs = [...css.matchAll(/var\((--[\w-]+)/g)].map((m) => m[1])
  return {
    name,
    files: {
      component: files.some((f) => f === `${name}.tsx`),
      cssModule: files.some((f) => f.endsWith('.module.css')),
      stories: files.some((f) => f.endsWith('.stories.tsx')),
      tests: files.some((f) => f.endsWith('.test.tsx')),
      codeConnect: files.some((f) => f.endsWith('.figma.tsx')),
    },
    componentTokens: new Set(refs.filter((r) => r.startsWith('--component-'))).size,
    coreTokens: new Set(refs.filter((r) => r.startsWith('--core-'))).size,
    usesIcons: /from '\.\.\/\.\.\/icons'/.test(src),
    usesPrimitives: /from '\.\.\/\.\.\/primitives/.test(src),
    uses: [...uses].sort(),
    usedBy: [],
    runtime: [...runtime].sort(),
  }
})
for (const c of data) for (const u of c.uses) data.find((x) => x.name === u)?.usedBy.push(c.name)
for (const c of data) c.usedBy.sort()
const primDir = join(root, 'src/primitives')
const primDom = existsSync(primDir) ? readdirSync(primDir).filter((f) => /\.tsx?$/.test(f) && /from 'react-dom/.test(readFileSync(join(primDir, f), 'utf8'))).map((f) => f.replace(/\.tsx?$/, '')) : []
const runtime = { react: data.filter((c) => c.runtime.includes('react')).length, 'react-dom': data.filter((c) => c.runtime.includes('react-dom')).map((c) => c.name) }
writeFileSync(join(root, 'src/preview/stackMap.json'), JSON.stringify({ components: data, runtime: { ...runtime, primitives: primDom } }, null, 1))

const yes = (b) => (b ? 'yes' : 'no')
const md = ['# Component map', '', 'Generated by `scripts/gen-stack-map.mjs`. Do not edit.', '',
  '## What each component is built with', '',
  '| Component | CSS Module | Stories | Tests | Code Connect | Component tokens | Core tokens | Icons | Runtime |', '|---|---|---|---|---|---|---|---|---|',
  ...data.map((c) => `| ${c.name} | ${yes(c.files.cssModule)} | ${yes(c.files.stories)} | ${yes(c.files.tests)} | ${yes(c.files.codeConnect)} | ${c.componentTokens} | ${c.coreTokens} | ${yes(c.usesIcons)} | ${c.runtime.join(', ') || 'none'} |`),
  '', '## Which components use each other', '', '| Component | Uses | Used by |', '|---|---|---|',
  ...data.map((c) => `| ${c.name} | ${c.uses.join(', ') || '-'} | ${c.usedBy.join(', ') || '-'} |`), '',
  `Runtime libraries: ${runtime.react} of ${data.length} components import React. react-dom is imported by ${runtime['react-dom'].join(', ') || 'none'}${primDom.length ? ` and by the shared primitive ${primDom.join(', ')}` : ''}. No other runtime library is imported by component code. Charts need Highcharts, installed by the Data-Viz package.`, '']
writeFileSync(join(root, 'docs/COMPONENT_MAP.md'), md.join('\n'))
console.log(`Stack map: ${data.length} components, ${data.reduce((a, c) => a + c.uses.length, 0)} component-to-component links`)
